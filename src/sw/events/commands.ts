// Keyboard command handlers.
// Only the two v1 commands are active; v2 command stubs are reserved.

/** Register command listeners. Called synchronously from index.ts on SW load. */
export function registerCommandListeners(): void {
  chrome.commands.onCommand.addListener((command) => {
    console.log('[Tabbary SW] command:', command);

    switch (command) {
      case 'open-full-tab':
        chrome.tabs.create({ url: chrome.runtime.getURL('index.html') });
        break;

      case 'open-tags':
        chrome.tabs.create({ url: chrome.runtime.getURL('tags.html') });
        break;

      case 'open-bookmarks':
        chrome.tabs.create({ url: chrome.runtime.getURL('bookmarks.html') });
        break;

      case 'open-side-panel':
        // Commands cannot open a panel from every context, so fall back to the
        // full-tab manager if there is no focused window to dock beside.
        chrome.windows.getLastFocused({ populate: false }, (win) => {
          if (win?.id !== undefined) {
            chrome.sidePanel.open({ windowId: win.id }).catch(() => {
              chrome.tabs.create({ url: chrome.runtime.getURL('index.html') });
            });
          } else {
            chrome.tabs.create({ url: chrome.runtime.getURL('index.html') });
          }
        });
        break;

      // v2 stubs — reserved for future binding
      // case 'close-session': ...
      // case 'activate-profile': ...
      // case 'activate-previous-tab': ...
      // case 'attach-tags': ...
      // case 'hot-tab-1': ...
      // case 'hot-tab-2': ...
      // case 'hot-tab-3': ...
      // case 'hot-tab-4': ...
      // case 'hot-tab-5': ...
      // case 'hot-tab-6': ...
      // case 'hot-tab-7': ...
      // case 'hot-tab-8': ...
      // case 'hot-tab-9': ...
      // case 'hot-tab-0': ...
      // case 'hot-bookmark-1': ...
      // case 'hot-bookmark-2': ...
      // case 'hot-bookmark-3': ...
      // case 'hot-bookmark-4': ...
      // case 'hot-bookmark-5': ...
      // case 'hot-bookmark-6': ...
      // case 'hot-bookmark-7': ...
      // case 'hot-bookmark-8': ...
      // case 'hot-bookmark-9': ...
      // case 'hot-bookmark-0': ...

      default:
        console.log('[Tabbary SW] unknown command:', command);
    }
  });
}